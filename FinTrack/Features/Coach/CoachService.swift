//
//  CoachService.swift
//  FinTrack — the money coach's model backend.
//
//  Ported from `askCoach()` in FinTrack.dc.html (L722-761). The prototype called the
//  hosted `window.claude.complete`; the shipping app talks to a LOCAL Ollama instance on
//  the host's loopback (Info.plist sets NSAllowsLocalNetworking so the simulator can reach
//  127.0.0.1). The system prompt, the snapshot it embeds and the offline text are the
//  prototype's, character for character.
